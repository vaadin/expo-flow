package com.example.application.views;

import com.example.application.data.entity.Person;
import com.example.application.data.repository.PersonRepository;
import com.vaadin.browserless.SpringBrowserlessTest;
import com.vaadin.flow.component.grid.Grid;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

@SpringBootTest
class PlaygroundViewTest extends SpringBrowserlessTest {

    @Autowired
    PersonRepository repository;

    @Test
    void gridShowsAllPersons() {
        navigate(PlaygroundView.class);

        @SuppressWarnings("unchecked")
        Grid<Person> grid = $(Grid.class).single();

        assertTrue(repository.count() > 0); // generated by DataGenerator on startup
        assertEquals(repository.count(), grid.getListDataView().getItemCount());
    }
}
